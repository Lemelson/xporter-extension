const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync('popup/theme-presets.js', 'utf8'), context);
const p = context.XPorterThemes;
assert.equal(p.presets.length, 11);
assert.equal(new Set(p.presets.map(v => v.id)).size, 11);
assert.equal(p.resolve({ theme: 'dark' }).id, 'classic-dark');
assert.equal(p.resolve({ theme: 'light', simplifiedDesign: true }).id, 'classic-light');
assert.equal(p.resolve({ theme: 'light', themePreset: 'unknown' }).id, 'classic-light');
assert.equal(p.resolve({ theme: 'dark', themePreset: 'cobalt' }).mode, 'light');
assert.equal(p.resolve({ themePreset: '<style>' }).id, 'classic-dark');
assert.equal(p.presets.find(v => v.id === 'cobalt').preview.button, '#ffffff');
assert.equal(p.presets.find(v => v.id === 'cobalt').preview.buttonText, '#101010');
assert.equal(p.presets.filter(v => v.mode === 'dark').length, 7);
assert.equal(p.presets.filter(v => v.mode === 'light').length, 4);
console.log('PASS: theme catalog, legacy/default recovery, invalid id fallback, mode ownership, cobalt action.');
